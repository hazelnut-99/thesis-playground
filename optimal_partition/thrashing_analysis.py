from collections import defaultdict


def parse_rebalance_events(event_string):
    events = []
    for line in event_string.split('\n'):
        if not line.strip():
            continue  # skip empty lines
        
        # Extract components using string splitting
        parts = line.split()
        request_id = int(parts[1])
        from_node = int(parts[3])
        to_node = int(parts[5])
        
        events.append((request_id, from_node, to_node))
    events.sort(key=lambda x: x[0])
    return events


def calc_thrashing_factor(events):
    outgoing = defaultdict(int)
    incoming = defaultdict(int)
        
    for id, src, dst in events:
        outgoing[src] += 1
        incoming[dst] += 1
    
    total_moves = len(events)
    nodes = set(outgoing.keys()).union(set(incoming.keys()))
    
    net_changes = {node: incoming.get(node, 0) - outgoing.get(node, 0) 
                    for node in nodes}

    abs_net_sum = sum(abs(net) for net in net_changes.values())
    net_effective_moves = abs_net_sum // 2
    
    thrashing_factor = (total_moves - net_effective_moves) / total_moves if total_moves > 0 else 0
    
    return total_moves, net_effective_moves, thrashing_factor
    


